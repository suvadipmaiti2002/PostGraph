from typing import List, Dict, Optional
from typing_extensions import TypedDict


class ResearchSource(TypedDict):
    title: str
    url: str
    content: str


class BlogState(TypedDict):
    topic: str                          # e.g. "Synchronous vs Asynchronous"
    audience: str                       # e.g. "Software Engineers"
    style: Optional[str]                # "intuitive" | "practical" | "deep"

    # Research Phase
    search_queries: List[str]           # 3 expanded queries generated by LLM
    research_sources: List[Dict[str, str]]  # List of [{"title": ..., "url": ..., "content": ...}]
    research_summary: str               # Structured outline produced by Researcher

    # Writing & Review Phase
    draft: str                          # Full markdown draft produced by Writer
    human_feedback: Optional[str]       # Comments/revision requests typed by the human
    revision_count: int                 # Safety counter: tracks revision cycles (guardrail)
    max_revisions: int                  # Maximum allowed revisions before forced advance 

    # Final Output
    final_blog: str                     # Fact-checked, polished blog with citations
    current_stage: str                  # Pipeline status for UI stepper tracking
